"""Write paper/appendix_secondary.tex: every row of outputs/stage3/results_secondary.csv, plus the top-10% p-value
summary that plan section 7 (S5) pairs with the reference-adjusted top-decile gap. Reads result tables only.
Run from the project root:  python scripts/make_appendix_secondary.py
"""
import sys, math
sys.path.insert(0, "scripts")
from csvio import read_csv_exact as R

d = R("outputs/stage3/results_secondary.csv")
m = R("outputs/stage3/competition_measures.csv")

def f(x):
    if x is None or (isinstance(x, float) and math.isnan(x)): return ""
    if x == 0: return "0"
    a = abs(x)
    s = f"{x:.3g}" if 1e-3 <= a < 1e4 else f"{x:.2e}"
    if "e" in s:
        b, e = s.split("e"); s = f"{b}\\times10^{{{int(e)}}}"
    return "$" + s.replace("-", "-") + "$"

def esc(t): return str(t).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace(">=", "$\\ge$").replace("<=", "$\\le$")

UNITS = {"drift_mean": "drift", "rel_drift": "relative drift", "rel_mean_gap": "relative gap",
         "abs_gap": "abs.\\ gap", "top10_gap_excess": "adj.\\ top-10\\% gap",
         "p05_all": "$p\\le0.05$, all", "p05_first": "$p\\le0.05$, first", "count": "count"}
rows = []
for a, g in d.groupby("analysis", sort=True):
    rows.append(f"\\midrule\n\\multicolumn{{7}}{{l}}{{\\textbf{{{a}}}}} \\\\")
    for _, r in g.iterrows():
        n = "" if (isinstance(r.n, float) and math.isnan(r.n)) else str(int(r.n))
        if not (isinstance(r.n_other, float) and math.isnan(r.n_other)): n += f"/{int(r.n_other)}"
        ci = f"({f(r.ci_lo)}, {f(r.ci_hi)})" if not (isinstance(r.ci_lo, float) and math.isnan(r.ci_lo)) else "--"
        rows.append(" & ".join([esc(r.group), UNITS.get(r.measure, esc(r.measure)), n, f(r["median"]), ci,
                                f(r.share_positive), f(r.p)]) + " \\\\")
# S5 pairing from plan section 7: top-10% p-values next to the reference-adjusted top-decile gap
acc = m[m.excluded.isna() & m.p05_top10.notna()]
rows.append("\\midrule\n\\multicolumn{7}{l}{\\textbf{S5, top decile (plan: shown only next to the adjusted gap)}} \\\\")
for c in ("O", "E"):
    x = acc[acc.Cohort == c]
    rows.append(" & ".join([c, "$p\\le0.05$, top 10\\%", str(len(x)), f(float(x.p05_top10.median())), "--",
                            f(float(x.top10_gap_excess.median())) + " (adj.\\ gap)", ""]) + " \\\\")

tex = r"""\section{All pre-specified secondary quantities}
\label{app:secondary}

{\raggedright
Every row of \texttt{outputs/stage3/results\_secondary.csv}, generated by \texttt{scripts/make\_appendix\_secondary.py}, and the top-decile $p$-value summary that the plan pairs with the reference-adjusted gap (from \texttt{competition\_measures.csv}). S1 regression and classification; S2 test-set size (accuracy); S3 platform within $E$; S4 deadline year within $E$; S5 formal accuracy test at minimum compatible sizes; S6, without flagged competitions, is in Table~\ref{tab:confirm} and Section~\ref{sec:confirm}. Estimate: median over competitions, a difference in medians (rows ``minus''), or a Spearman correlation (rows ``Spearman''). Intervals: 95\% bootstrap over competitions; ``--'' where none was computed (Spearman rows, a departure from the plan; counts). Units: drift in the metric's own units (accuracy as a fraction); relative quantities in team spreads; accuracy gaps as fractions (0.01 is one percentage point). $n$: competitions, or the two groups' sizes; relative quantities exclude competitions without a team spread, so their $n$ can be smaller than for raw drift. Share: share of competitions with a positive value (shown without interval). $p$: Mann--Whitney for differences, Spearman test for correlations. Not confirmatory; not corrected for multiplicity.\par}

{\scriptsize\setlength{\tabcolsep}{2.5pt}
\begin{longtable}{>{\raggedright\arraybackslash}p{4.1cm}>{\raggedright\arraybackslash}p{1.9cm}p{1.1cm}p{1.9cm}p{3.5cm}p{0.9cm}p{1.6cm}}
\toprule
Group & Quantity & $n$ & Estimate & 95\% interval & Share $>0$ & $p$ \\
\midrule
\endfirsthead
\toprule
Group & Quantity & $n$ & Estimate & 95\% interval & Share $>0$ & $p$ \\
\midrule
\endhead
""" + "\n".join(rows) + r"""
\bottomrule
\end{longtable}}
"""
open("paper/appendix_secondary.tex", "w").write(tex)
print(len(d), "rows written")
