"""Write paper/appendix_secondary.tex: every row of outputs/stage3/results_secondary.csv (S1-S5), the S5 top-decile
summary that plan section 7 pairs with the reference-adjusted gap, and the S6 rows of results_confirmatory.csv.
Reads result tables only. Run from the project root:  python scripts/make_appendix_secondary.py
"""
import sys, math
sys.path.insert(0, "scripts")
from csvio import read_csv_exact as R

d = R("outputs/stage3/results_secondary.csv")
m = R("outputs/stage3/competition_measures.csv")
c = R("outputs/stage3/results_confirmatory.csv")

def isnan(x): return x is None or (isinstance(x, float) and math.isnan(x))

def f(x):
    if isnan(x): return ""
    if x == 0: return "0"
    a = abs(x)
    s = f"{x:.3g}" if 1e-3 <= a < 1e4 else f"{x:.2e}"
    if "e" in s:
        b, e = s.split("e"); s = f"{b}\\times10^{{{int(e)}}}"
    return "$" + s + "$"

def esc(t): return str(t).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")

UNITS = {"drift_mean": "drift", "rel_drift": "relative drift", "rel_mean_gap": "relative gap",
         "abs_gap": "abs.\\ gap", "top10_gap_excess": "adj.\\ top-10\\% gap",
         "p05_all": "$p\\le0.05$, all", "p05_first": "$p\\le0.05$, first", "count": "count"}
rows = []
for a, g in d.groupby("analysis", sort=True):
    rows.append(f"\\midrule\n\\multicolumn{{7}}{{l}}{{\\textbf{{{a}}}}} \\\\")
    for _, r in g.iterrows():
        n = "" if isnan(r.n) else str(int(r.n))
        if not isnan(r.n_other): n += f"/{int(r.n_other)}"
        ci = "--" if isnan(r.ci_lo) else f"({f(r.ci_lo)}, {f(r.ci_hi)})"
        rows.append(" & ".join([esc(r.group), UNITS.get(r.measure, esc(r.measure)), n, f(r["median"]), ci,
                                f(r.share_positive), f(r.p)]) + " \\\\")

acc = m[m.excluded.isna() & m.p05_top10.notna()]
s5rows = []
for coh in ("O", "E"):
    x = acc[acc.Cohort == coh]
    s5rows.append(" & ".join([f"${coh}$", str(len(x)), f(float(x.p05_top10.median())),
                              f(float(x.top10_gap_excess.median()))]) + " \\\\")

LABEL = {"H1a accuracy mean gap": "H1a accuracy, median gap", "H1b AUC mean gap": "H1b AUC, median gap",
         "H2 drift exists in E (all metrics)": "H2 share with positive drift",
         "H3 relative drift, five metric groups": "H3 median relative drift"}
s6rows = []
for _, r in c[c["sample"] == "S6 not flagged"].iterrows():
    n = f"{int(r.n_E)}" + ("" if isnan(r.n_O) else f"/{int(r.n_O)}")
    s6rows.append(" & ".join([LABEL[r.test], esc(r.effect), n, f(r.estimate), f"({f(r.ci_lo)}, {f(r.ci_hi)})",
                              f(r.p_holm)]) + " \\\\")

HEAD = "Group & Quantity & $n$ & Estimate & 95\\% interval & Share $>0$ & $p$ \\\\\n\\midrule\n"
tex = ("\\section{All pre-specified secondary quantities}\n\\label{app:secondary}\n\n{\\raggedright\n"
"Table~\\ref{tab:secondary} lists every row of \\texttt{outputs/stage3/results\\_secondary.csv} (S1 regression and "
"classification; S2 test-set size, accuracy; S3 platform within $E$; S4 deadline year within $E$; S5 formal accuracy test "
"at minimum compatible sizes). Table~\\ref{tab:s5} gives the top-decile summary that the plan pairs with the "
"reference-adjusted gap, and Table~\\ref{tab:s6} the S6 tests without flagged competitions. All three are generated by "
"\\texttt{scripts/make\\_appendix\\_secondary.py} from the result tables. "
"Estimate: median over competitions, a difference in medians (rows ``minus''), a Spearman correlation (rows "
"``Spearman''), or a proportion of competitions (rows ``above 0.10''). Intervals: 95\\% bootstrap over competitions; "
"``--'' where none was computed (Spearman rows and counts). Shares of positive values and the summaries in "
"Table~\\ref{tab:s5} also have no intervals; these omissions depart from the plan's general promise of intervals. "
"Units: drift in the metric's own units (accuracy as a fraction); relative quantities in team spreads; accuracy gaps "
"as fractions (0.01 is one percentage point). $n$: competitions, or the two groups' sizes; relative quantities exclude "
"competitions without a team spread, so their $n$ can be smaller than for raw drift. Share: share of competitions with "
"a positive value. $p$: Mann--Whitney for differences, Spearman test for correlations. Not confirmatory; not corrected "
"for multiplicity.\\par}\n\n"
"{\\scriptsize\\setlength{\\tabcolsep}{2.5pt}\n"
"\\begin{longtable}{>{\\raggedright\\arraybackslash}p{4.1cm}>{\\raggedright\\arraybackslash}p{1.9cm}p{1.1cm}p{1.9cm}p{3.5cm}p{0.9cm}p{1.6cm}}\n"
"\\caption{S1--S5: every row of the secondary results table.}\\label{tab:secondary}\\\\\n"
"\\toprule\n" + HEAD + "\\endfirsthead\n\\toprule\n" + HEAD + "\\endhead\n"
+ "\n".join(rows) + "\n\\bottomrule\n\\end{longtable}}\n\n"
"\\begin{table}[!t]\n\\centering\\small\n"
"\\caption{S5, top decile, as the plan specifies: median share of top-10\\% submissions with $p\\le0.05$, next to the "
"median reference-adjusted top-decile gap (accuracy as a fraction). Accuracy competitions with minimum compatible "
"sizes. No intervals.}\\label{tab:s5}\n"
"\\begin{tabular}{llll}\n\\toprule\nCohort & $n$ & Share $p\\le0.05$, top 10\\% & Adjusted top-decile gap \\\\\n\\midrule\n"
+ "\n".join(s5rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n\n"
"\\begin{table}[!t]\n\\centering\\small\n"
"\\caption{S6: the four confirmatory tests repeated without flagged competitions (a secondary analysis). Effects as in "
"Table~\\ref{tab:confirm}; accuracy in percentage points; relative drift in team spreads. $p$-values Holm-corrected "
"within these four. $n$: $E$, or $E$/$O$, competitions.}\\label{tab:s6}\n"
"\\begin{tabular}{llllll}\n\\toprule\nTest & Effect & $n$ & Estimate & 95\\% interval & $p$ \\\\\n\\midrule\n"
+ "\n".join(s6rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
open("paper/appendix_secondary.tex", "w").write(tex)
print(len(d), "secondary rows;", len(s5rows), "S5 rows;", len(s6rows), "S6 rows")
